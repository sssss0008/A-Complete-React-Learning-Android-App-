@Composable
fun LearnReactTheme(
    darkTheme: Boolean = true, // Default to sleek developer dark mode as requested
    dynamicColor: Boolean = false, // Preserve branded React Cyan & Dark Navy developer styling
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
